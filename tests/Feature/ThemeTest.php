<?php

// torsade/tests/Feature/ThemeTest.php

namespace Tests\Feature;

use PHPUnit\Framework\Attributes\DataProvider;
use Symfony\Component\Finder\Finder;
use Tests\TestCase;

/**
 * Colours live in one file, the one that defines the themes. Components
 * only use the names declared there, and the pairs of colours that carry a
 * text or mark a field keep enough contrast in both themes.
 */
class ThemeTest extends TestCase
{
    private const THEME_FILE = 'css/app.css';

    /**
     * What a colour written outside of the theme file looks like.
     */
    private const HARD_CODED = [
        'hexadecimal value' => '/#[0-9a-fA-F]{3,8}\b/',
        'colour function' => '/\b(?:rgba?|hsla?|hwb|lab|lch|oklab|oklch|color)\(/',
        'class of the default Tailwind palette' => '/\b(?:bg|text|border|ring|fill|stroke|from|to|via|outline|decoration|divide|shadow|accent|caret|placeholder)-(?:slate|gray|zinc|neutral|stone|red|orange|amber|yellow|lime|green|emerald|teal|cyan|sky|blue|indigo|violet|purple|fuchsia|pink|rose|white|black)(?:-\d{2,3})?\b/',
    ];

    public function test_no_colour_is_written_outside_of_the_theme_file(): void
    {
        $files = Finder::create()
            ->files()
            ->in(resource_path())
            // Generated by Wayfinder from the registered routes.
            ->exclude(['js/actions', 'js/routes', 'js/wayfinder'])
            ->notPath(self::THEME_FILE);

        $this->assertGreaterThan(50, $files->count());

        $found = [];

        foreach ($files as $file) {
            foreach (explode("\n", $file->getContents()) as $number => $line) {
                foreach (self::HARD_CODED as $kind => $pattern) {
                    if (preg_match($pattern, $line, $match) === 1) {
                        $found[] = sprintf('%s:%d: %s "%s"', $file->getRelativePathname(), $number + 1, $kind, $match[0]);
                    }
                }
            }
        }

        $this->assertSame([], $found, 'Colours are only defined in resources/'.self::THEME_FILE.'.');
    }

    public function test_the_check_recognises_a_hard_coded_colour(): void
    {
        $samples = [
            'color: #2F6FCF;',
            'background: #fff',
            'color: rgb(0 0 0 / 50%)',
            'color: hsl(0 0% 9%)',
            'background-color: oklch(0.145 0 0);',
            'class="bg-neutral-100 p-1"',
            'class="text-red-600"',
            'class="hover:text-black"',
            'class="bg-black/80"',
        ];

        foreach ($samples as $sample) {
            $this->assertTrue(
                array_any(self::HARD_CODED, fn (string $pattern): bool => preg_match($pattern, $sample) === 1),
                $sample.' is not recognised.',
            );
        }

        // Names of the theme and slot names are not colours.
        foreach (['class="bg-pair-orange text-on-success"', '<template #default="{ errors }">', 'class="border-border-strong"'] as $sample) {
            $this->assertFalse(
                array_any(self::HARD_CODED, fn (string $pattern): bool => preg_match($pattern, $sample) === 1),
                $sample.' is taken for a colour.',
            );
        }
    }

    /**
     * @return array<string, array{string, string, float}>
     */
    public static function pairs(): array
    {
        $pairs = [];

        // Texts: 4.5:1 on each background they are written on.
        $texts = [
            'foreground' => ['background', 'card', 'popover', 'sunken', 'muted', 'sidebar-background', 'error-surface', 'success-panel'],
            'muted-foreground' => ['background', 'card', 'sunken', 'muted', 'sidebar-background'],
            'subtle-foreground' => ['background', 'card', 'sunken', 'sidebar-background'],
            'link' => ['background', 'card', 'sunken', 'sidebar-background'],
            'error' => ['background', 'card', 'sunken', 'error-surface'],
            'success' => ['background', 'card', 'success-surface', 'success-panel'],
            'vlan' => ['vlan-surface'],
            // The words of a deviation, on a page or in a line of a table.
            'pair-orange' => ['background', 'card'],
            'primary-foreground' => ['primary'],
            'destructive-foreground' => ['destructive'],
            'on-success' => ['pair-green'],
            'accent-foreground' => ['accent'],
            'secondary-foreground' => ['secondary'],
            'sidebar-foreground' => ['sidebar-background'],
            'sidebar-accent-foreground' => ['sidebar-accent'],
        ];

        // Borders of fields, focus, cells of the address plan, status
        // marks: 3:1 against what surrounds them.
        $marks = [
            'input' => ['background', 'card'],
            'ring' => ['background', 'card', 'sunken', 'sidebar-background'],
            'destructive' => ['background', 'card'],
            'plan-free' => ['sunken'],
            'plan-documented' => ['sunken'],
            'pair-orange' => ['sunken', 'background', 'card', 'vlan-surface'],
            'pair-green' => ['sunken', 'background', 'card', 'sidebar-accent'],
            'pair-brown' => ['sunken', 'background'],
            'link' => ['sunken', 'background', 'card'],
        ];

        foreach (['4.5' => $texts, '3' => $marks] as $minimum => $group) {
            foreach ($group as $colour => $backgrounds) {
                foreach ($backgrounds as $background) {
                    $pairs["{$colour} on {$background}, {$minimum}:1"] = [$colour, $background, (float) $minimum];
                }
            }
        }

        return $pairs;
    }

    #[DataProvider('pairs')]
    public function test_a_pair_of_colours_has_enough_contrast_in_both_themes(string $colour, string $background, float $minimum): void
    {
        foreach (self::themes() as $theme => $variables) {
            $ratio = self::contrast(self::colour($variables, $colour), self::colour($variables, $background));

            $this->assertGreaterThanOrEqual(
                $minimum,
                $ratio,
                sprintf('%s theme: --%s on --%s reaches %.2f:1.', $theme, $colour, $background, $ratio),
            );
        }
    }

    public function test_the_qr_code_is_dark_on_white_in_both_themes(): void
    {
        $themes = self::themes();

        foreach ($themes as $theme => $variables) {
            $this->assertSame('#ffffff', self::colour($variables, 'qr-background'), "{$theme} theme");

            // Far beyond what a text needs: a camera has to read it.
            $this->assertGreaterThanOrEqual(
                12,
                self::contrast(self::colour($variables, 'qr-module'), self::colour($variables, 'qr-background')),
                "{$theme} theme",
            );
        }

        // The same two colours whatever the theme: the dark theme does not
        // redefine them.
        $this->assertSame($themes['light']['qr-background'], $themes['dark']['qr-background']);
        $this->assertSame($themes['light']['qr-module'], $themes['dark']['qr-module']);

        $css = (string) file_get_contents(resource_path(self::THEME_FILE));

        $this->assertSame(1, substr_count($css, '--qr-background:'));
        $this->assertSame(1, substr_count($css, '--qr-module:'));
    }

    public function test_both_themes_define_the_same_colours(): void
    {
        $themes = self::themes();

        $this->assertSame(array_keys($themes['light']), array_keys($themes['dark']));
        $this->assertGreaterThan(40, count($themes['light']));

        foreach ($themes as $variables) {
            foreach (array_keys($variables) as $name) {
                $this->assertMatchesRegularExpression('/^#[0-9a-f]{6}$/', self::colour($variables, $name));
            }
        }
    }

    /**
     * The colour variables of each theme. The dark theme is declared as
     * what it changes in the light one.
     *
     * @return array{light: array<string, string>, dark: array<string, string>}
     */
    private static function themes(): array
    {
        $css = (string) file_get_contents(resource_path(self::THEME_FILE));

        $light = self::declarations($css, ':root');
        // Printed, a page may ask for the light theme: the dark one then
        // steps aside.
        $dark = array_merge($light, self::declarations($css, '.dark:not(.print-light)'));

        return ['light' => $light, 'dark' => $dark];
    }

    /**
     * @return array<string, string>
     */
    private static function declarations(string $css, string $selector): array
    {
        if (preg_match('/^'.preg_quote($selector, '/').'\s*\{(.*?)^\}/ms', $css, $block) !== 1) {
            self::fail("The theme file has no {$selector} block.");
        }

        preg_match_all('/^\s*--([a-z0-9-]+)\s*:\s*([^;]+);/m', $block[1], $matches, PREG_SET_ORDER);

        $declarations = [];

        foreach ($matches as $match) {
            $declarations[$match[1]] = strtolower(trim($match[2]));
        }

        return $declarations;
    }

    /**
     * The value of a variable, following the variables it refers to.
     *
     * @param  array<string, string>  $variables
     */
    private static function colour(array $variables, string $name): string
    {
        $value = $variables[$name] ?? self::fail("The theme does not define --{$name}.");

        if (preg_match('/^var\(--([a-z0-9-]+)\)$/', $value, $reference) === 1) {
            return self::colour($variables, $reference[1]);
        }

        return $value;
    }

    /**
     * Contrast ratio of two colours, as defined by WCAG 2.
     */
    private static function contrast(string $first, string $second): float
    {
        $lighter = max(self::luminance($first), self::luminance($second));
        $darker = min(self::luminance($first), self::luminance($second));

        return ($lighter + 0.05) / ($darker + 0.05);
    }

    private static function luminance(string $hexadecimal): float
    {
        $channels = array_map(
            function (string $channel): float {
                $value = hexdec($channel) / 255;

                return $value <= 0.04045 ? $value / 12.92 : (($value + 0.055) / 1.055) ** 2.4;
            },
            str_split(ltrim($hexadecimal, '#'), 2),
        );

        return 0.2126 * $channels[0] + 0.7152 * $channels[1] + 0.0722 * $channels[2];
    }
}
