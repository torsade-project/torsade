<?php

// torsade/tests/Feature/Auth/RemovedFeaturesTest.php

namespace Tests\Feature\Auth;

use App\Models\User;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Support\Facades\Route;
use PHPUnit\Framework\Attributes\DataProvider;
use Symfony\Component\Finder\Finder;
use Tests\TestCase;

/**
 * Public registration, password reset by e-mail and e-mail verification are
 * removed from the starter kit: their URLs must not exist at all.
 */
class RemovedFeaturesTest extends TestCase
{
    use RefreshDatabase;

    /**
     * @return array<string, array{string, string}>
     */
    public static function removedUrls(): array
    {
        return [
            'registration form' => ['get', '/register'],
            'registration' => ['post', '/register'],
            'password reset request form' => ['get', '/forgot-password'],
            'password reset request' => ['post', '/forgot-password'],
            'password reset form' => ['get', '/reset-password/some-token'],
            'password reset' => ['post', '/reset-password'],
            'email verification notice' => ['get', '/email/verify'],
            'email verification link' => ['get', '/email/verify/1/some-hash'],
            'email verification resend' => ['post', '/email/verification-notification'],
        ];
    }

    #[DataProvider('removedUrls')]
    public function test_removed_urls_answer_404_to_guests(string $method, string $uri): void
    {
        $this->call($method, $uri)->assertNotFound();
    }

    #[DataProvider('removedUrls')]
    public function test_removed_urls_answer_404_to_authenticated_users(string $method, string $uri): void
    {
        $this->actingAs(User::factory()->create())
            ->call($method, $uri)
            ->assertNotFound();
    }

    public function test_no_route_is_registered_for_the_removed_features(): void
    {
        foreach ([
            'register',
            'register.store',
            'password.request',
            'password.email',
            'password.reset',
            'password.update',
            'verification.notice',
            'verification.verify',
            'verification.send',
        ] as $name) {
            $this->assertFalse(Route::has($name), "Route [{$name}] should not exist.");
        }
    }

    public function test_the_login_page_receives_no_link_to_the_removed_features(): void
    {
        $this->get(route('login'))
            ->assertInertia(fn ($page) => $page
                ->component('auth/Login')
                ->missing('canResetPassword')
                ->missing('canRegister'),
            );
    }

    public function test_no_interface_file_links_to_the_removed_features(): void
    {
        $files = Finder::create()
            ->files()
            ->in([resource_path('js'), resource_path('views')])
            // Generated by Wayfinder from the registered routes.
            ->exclude(['actions', 'routes', 'wayfinder'])
            ->name(['*.vue', '*.ts', '*.php']);

        $this->assertGreaterThan(0, $files->count());

        foreach ($files as $file) {
            // URLs and typed route modules of the removed features. The
            // administrator's own "reset password" action is not one of them.
            $this->assertDoesNotMatchRegularExpression(
                '~/register\b|forgot-password|["\'`]/reset-password|email/verif|routes/register|routes/verification|routes/password/(request|email|reset)~',
                $file->getContents(),
                $file->getRelativePathname().' links to a removed feature.',
            );
        }
    }
}
