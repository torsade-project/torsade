<?php

// torsade/tests/Feature/TranslationTest.php

namespace Tests\Feature;

use App\Models\User;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Support\Arr;
use Illuminate\Support\ViewErrorBag;
use Symfony\Component\Finder\Finder;
use Tests\TestCase;

/**
 * The interface is in French and every string goes through the translation
 * system: lang/fr.json for the interface, lang/fr/*.php for the framework.
 */
class TranslationTest extends TestCase
{
    use RefreshDatabase;

    private function error(string $field): string
    {
        $errors = session('errors');

        // Once saved, the JSON session keeps the error bags as plain arrays.
        return $errors instanceof ViewErrorBag
            ? $errors->first($field)
            : (string) data_get($errors, "default.messages.{$field}.0", '');
    }

    /**
     * @return array<string, string>
     */
    private function catalogue(): array
    {
        return json_decode((string) file_get_contents(lang_path('fr.json')), true, flags: JSON_THROW_ON_ERROR);
    }

    /**
     * Collect the keys passed as a string literal to the given functions.
     *
     * @param  list<string>  $directories
     * @param  list<string>  $names
     * @return list<string>
     */
    private function keysUsedIn(array $directories, array $names, string $functions): array
    {
        $files = Finder::create()
            ->files()
            ->in($directories)
            // Generated by Wayfinder from the registered routes.
            ->exclude(['actions', 'routes', 'wayfinder'])
            ->name($names);

        $keys = [];

        foreach ($files as $file) {
            preg_match_all(
                '~(?:'.$functions.')\(\s*([\'"])((?:\\\\.|(?!\1).)*)\1~s',
                $file->getContents(),
                $matches,
            );

            foreach ($matches[2] as $key) {
                $keys[] = stripslashes($key);
            }
        }

        return array_values(array_unique($keys));
    }

    public function test_the_application_locale_is_french(): void
    {
        $this->assertSame('fr', app()->getLocale());

        $this->get(route('login'))->assertSee('<html lang="fr"', false);
    }

    public function test_validation_messages_are_in_french(): void
    {
        $this->post(route('login.store'), ['email' => '', 'password' => '']);

        $this->assertSame('Le champ adresse e-mail est obligatoire.', $this->error('email'));
        $this->assertSame('Le champ mot de passe est obligatoire.', $this->error('password'));
    }

    public function test_the_login_failure_message_is_in_french(): void
    {
        $this->post(route('login.store'), ['email' => 'nobody@example.com', 'password' => 'wrong-password']);

        $this->assertSame('Ces identifiants ne correspondent à aucun compte actif.', $this->error('email'));
    }

    public function test_the_lock_message_is_in_french(): void
    {
        foreach (range(1, 6) as $attempt) {
            $this->post(route('login.store'), ['email' => 'nobody@example.com', 'password' => 'wrong-password']);
        }

        $this->assertStringStartsWith('Trop de tentatives de connexion.', $this->error('email'));
    }

    public function test_the_password_length_message_is_in_french(): void
    {
        $this->actingAs(User::factory()->create())
            ->put(route('user-password.update'), [
                'current_password' => 'password',
                'password' => 'too-short',
                'password_confirmation' => 'too-short',
            ]);

        $this->assertSame('Le champ mot de passe doit contenir au moins 12 caractères.', $this->error('password'));
    }

    public function test_error_pages_are_in_french(): void
    {
        $this->get('/this-page-does-not-exist')
            ->assertNotFound()
            ->assertSee('Page introuvable');

        $this->actingAs(User::factory()->reader()->create())
            ->get(route('users.index'))
            ->assertForbidden()
            ->assertSee("Cette action n'est pas autorisée.");
    }

    public function test_every_framework_message_has_a_french_translation(): void
    {
        $frameworkLang = base_path('vendor/laravel/framework/src/Illuminate/Translation/lang/en');

        foreach (['auth', 'pagination', 'passwords', 'validation'] as $group) {
            $english = Arr::dot(Arr::except(require "{$frameworkLang}/{$group}.php", ['custom', 'attributes']));
            $french = Arr::dot(require lang_path("fr/{$group}.php"));

            $this->assertSame(
                [],
                array_values(array_diff(array_keys($english), array_keys($french))),
                "lang/fr/{$group}.php is missing framework keys.",
            );

            foreach (array_keys($english) as $key) {
                $this->assertNotSame($english[$key], $french[$key], "[{$group}.{$key}] is not translated.");
            }
        }
    }

    public function test_every_interface_string_has_a_french_translation(): void
    {
        $used = [
            ...$this->keysUsedIn([resource_path('js')], ['*.vue', '*.ts'], '\$tc?|\btrans(?:Choice)?'),
            ...$this->keysUsedIn([app_path(), base_path('routes'), resource_path('views')], ['*.php'], '\b__|\btrans_choice'),
            ...$this->keysUsedIn([base_path('vendor/laravel/fortify/src')], ['*.php'], '\b__'),
        ];

        $this->assertNotEmpty($used);

        // A key such as "auth.throttle" is a message of the framework: it
        // lives in lang/fr/auth.php, not in the catalogue of the interface.
        $used = array_filter(
            $used,
            fn (string $key): bool => ! (preg_match('/^[a-z]+\.[a-z_.]+$/', $key) === 1 && trans()->hasForLocale($key, 'fr')),
        );

        $this->assertSame(
            [],
            array_values(array_diff($used, array_keys($this->catalogue()))),
            'These strings are used but missing from lang/fr.json.',
        );
    }

    public function test_no_translation_is_left_empty_or_in_english(): void
    {
        foreach ($this->catalogue() as $key => $translation) {
            $this->assertNotSame('', trim($translation), "[{$key}] has an empty translation.");

            // Identical text is only acceptable for words shared by both languages.
            if ($key === $translation) {
                $this->assertContains(
                    $key,
                    [
                        ':role, version :version', 'Action', 'Actions', 'Administration', 'Catalogue', 'Code', 'Console', 'Date', 'Description', 'DHCP', 'Fibre', 'Internet', 'Loopback',
                        'NAS', 'Organisation', 'Pagination', 'Segment', 'Site', 'Site :name', 'Sites', 'Switch', 'Tunnel', 'Type',
                        'Site|Sites', 'VID', 'VLAN', 'VLAN :label',
                        // Notations of connectors, speeds, power standards
                        // and protocols, written the same everywhere.
                        'RJ45', 'SFP', 'SFP+', 'SFP28', 'QSFP+', 'QSFP28',
                        '100 Mbit/s', '1 Gbit/s', '5 Gbit/s', '10 Gbit/s', '25 Gbit/s', '40 Gbit/s', '100 Gbit/s',
                        '802.3af', '802.3at', '802.3bt Type 3', '802.3bt Type 4',
                        'LACP', 'Trunk', 'PoE', 'Port', 'Ports', ':count port|:count ports', 'Mode', 'Port :name',
                    ],
                    "[{$key}] is not translated.",
                );
            }
        }
    }

    public function test_components_contain_no_hard_coded_interface_text(): void
    {
        $files = Finder::create()->files()->in(resource_path('js'))->name('*.vue');

        $this->assertGreaterThan(0, $files->count());

        foreach ($files as $file) {
            $template = (string) preg_replace('~<script\b.*?</script>|<style\b.*?</style>~s', '', $file->getContents());
            $template = (string) preg_replace('~<!--.*?-->~s', '', $template);

            // Literal (unbound) attributes that are shown or read to the user.
            preg_match_all(
                '~(?<![:\w-])(?:placeholder|title|alt|label|description|aria-label)="([^"]*\p{L}[^"]*)"~u',
                $template,
                $attributes,
            );

            $this->assertSame([], $attributes[1], $file->getRelativePathname().' has hard-coded attribute text.');

            // Text nodes: what is left once attribute values, interpolations
            // and tags are removed.
            $text = (string) preg_replace('~="[^"]*"~s', '=""', $template);
            $text = (string) preg_replace('~\{\{.*?\}\}~s', '', $text);
            $text = (string) preg_replace('~<[^>]*>~s', '', $text);
            $text = html_entity_decode($text);

            $this->assertDoesNotMatchRegularExpression(
                '~\p{L}{2,}~u',
                $text,
                $file->getRelativePathname().' has hard-coded text in its template.',
            );
        }
    }
}
