<?php

// torsade/tests/Feature/NoExternalResourcesTest.php

namespace Tests\Feature;

use Symfony\Component\Finder\Finder;
use Tests\TestCase;

/**
 * Torsade must work on a network without Internet access: the interface may
 * not reference any external host (CDN, remote font, tracker, external link).
 */
class NoExternalResourcesTest extends TestCase
{
    /**
     * URLs that are identifiers or local fallbacks, never fetched from outside.
     */
    private const ALLOWED = [
        'http://www.w3.org/',
        'http://localhost',
    ];

    public function test_interface_sources_reference_no_external_host(): void
    {
        $files = Finder::create()
            ->files()
            ->in([resource_path('js'), resource_path('css'), resource_path('views')])
            // Generated by Wayfinder from the registered routes.
            ->exclude(['actions', 'routes', 'wayfinder']);

        $this->assertGreaterThan(0, $files->count());

        foreach ($files as $file) {
            preg_match_all('~(?:https?:)?//[a-z0-9][a-z0-9.-]*\.[a-z]{2,}[^\s"\'`)<]*~i', $file->getContents(), $matches);

            $external = array_filter(
                $matches[0],
                fn (string $url): bool => ! array_any(self::ALLOWED, fn (string $allowed): bool => str_starts_with($url, $allowed)),
            );

            $this->assertSame(
                [],
                array_values($external),
                $file->getRelativePathname().' references an external host.',
            );
        }
    }

    public function test_the_page_shell_loads_only_local_assets(): void
    {
        $html = $this->get(route('login'))->assertOk()->getContent();

        preg_match_all('~(?:src|href)="([^"]+)"~', (string) $html, $matches);

        $this->assertNotEmpty($matches[1]);

        foreach ($matches[1] as $url) {
            $host = parse_url($url, PHP_URL_HOST);

            $this->assertTrue(
                $host === null || $host === parse_url((string) config('app.url'), PHP_URL_HOST) || $host === 'localhost',
                "The page loads [{$url}] from an external host.",
            );
        }
    }

    public function test_no_font_is_downloaded_at_build_time(): void
    {
        $this->assertStringNotContainsString('laravel-vite-plugin/fonts', (string) file_get_contents(base_path('vite.config.ts')));
        $this->assertStringNotContainsString('@fonts', (string) file_get_contents(resource_path('views/app.blade.php')));
    }
}
